"""Generation strategies (the behaviour policies pi_b) and the on-disk layout that
carries them.

WHAT CHANGED (2026-09-06)
The C++ generator grew `--dataset_generation {BFS,DFS,S_DFS,HFS}` (commit b71b992).
Before it, every table was a stochastic-DFS sample and the four behaviour policies
were SYNTHESISED over that one tree (`policies.py`: bfs/dfs/hfs_oracle/random rank
the same DFS tree by depth / -depth / delta / U(0,1)). Now each behaviour policy has
its OWN tree, generated by the real search, so:

    one reconstructed tree PER (instance, strategy)   -- `tree.load_tree_instance`
    fringes are rolled inside THAT tree                -- `env.FringeEnv`
    the behaviour ranking is the generator's own       -- `policies.TRACE_POLICY`
    expansion order, recovered from the table

The user decides which pi_b enter training by deciding which strategies to
GENERATE (`create_all_training_data.py --dataset-generation ...`) and, optionally,
by restricting further at training time (`train_models.py --strategies ...`). A
strategy that was asked for but not generated is an ERROR here, never a silent
fallback to whatever is on disk.

ON-DISK LAYOUT (owned by scripts/gnn_exp/create_training_data.py)

    <exp>/_models/<domain>/training_data/<STRAT>/<instance>/<instance>_<TOKEN>_depth_<D>.csv
    <exp>/_models/<domain>/training_data/<instance>/<instance>_depth_<D>.csv        (LEGACY)

`<STRAT>` is the C++ enum spelling (BFS, DFS, S_DFS, HFS). `<TOKEN>` is what the C++
embeds in the CSV name: BFS / DFS / S_DFS / HFS_SUBGOALS_ (the heuristic is appended,
so the HFS token ends in `_` and the file reads `..._HFS_SUBGOALS__depth_25.csv` with
a DOUBLE underscore). Legacy tables carry no token: they predate the flag, so they
are S_DFS by construction (the DFS worker was the only generator).

WHY THE STRATEGY IS A DIRECTORY LEVEL AND NOT JUST THE FILE NAME
`create_training_data.py` moves each C++ run to `<target>/<instance>/` and rmtree's
whatever is there, and the DOT files inside `RawFiles/` are numbered per run
(`000001.dot`, ...). Two strategies in one instance folder would overwrite each
other's DOTs while both CSVs kept pointing at them. The strategy level keeps every
run self-contained.

The instance name is ALWAYS the CSV's parent directory (that is what `config_of`,
`expected_optimal` and the problem-file lookup parse), never the file name.

THIS MODULE OWNS NO GENERATION PARAMETER. It names strategies and finds tables.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

# Canonical (Python-side) ids, lowercase. Order = the order results are reported in.
STRATEGIES: Tuple[str, ...] = ("bfs", "dfs", "s_dfs", "hfs")

# The C++ enum spelling == the directory name on disk.
_DIR_NAME = {"bfs": "BFS", "dfs": "DFS", "s_dfs": "S_DFS", "hfs": "HFS"}
_FROM_DIR = {v: k for k, v in _DIR_NAME.items()}

# What a legacy (token-less) table is. Not a default in the "second opinion" sense:
# before b71b992 the DFS worker was the ONLY generator, so a token-less table cannot
# be anything else.
LEGACY_STRATEGY = "s_dfs"

# Separator between instance and strategy in a tree name. Chosen so that
# `name.rsplit("__pl_", 1)[0]` (selection.config_of) and the `__pl_(\d+)` regex
# (usability.expected_optimal) keep working on the composite name.
NAME_SEP = "@"

_TOKEN_RE = re.compile(r"_(BFS|DFS|S_DFS|HFS(?:_[A-Za-z0-9]+)*?_?)_depth_\d+\.csv$")
_DEPTH_RE = re.compile(r"_depth_(\d+)\.csv$")


def normalize_strategy(value: str) -> str:
    """User spellings (S-DFS, s_dfs, bfs, HFS ...) -> canonical id. Raises on junk."""
    v = str(value).strip().lower().replace("-", "_")
    if v not in STRATEGIES:
        raise ValueError(
            f"unknown generation strategy {value!r}; expected one of "
            f"{list(STRATEGIES)} (case-insensitive, '-' == '_')"
        )
    return v


def dir_name(strategy: str) -> str:
    """Canonical id -> the directory the generator writes (== C++ enum spelling)."""
    return _DIR_NAME[normalize_strategy(strategy)]


def strategy_from_dir_name(name: str) -> Optional[str]:
    """`BFS` -> `bfs`; anything that is not a strategy directory -> None."""
    return _FROM_DIR.get(name)


def strategy_from_csv_name(filename: str) -> Optional[str]:
    """Parse the token the C++ embeds in the CSV name.

    `CC_2_2_3__pl_4_BFS_depth_20.csv`            -> `bfs`
    `CC_2_2_3__pl_4_S_DFS_depth_20.csv`          -> `s_dfs`
    `CC_2_2_3__pl_4_HFS_SUBGOALS__depth_20.csv`  -> `hfs`
    `CC_2_2_3__pl_4_depth_25.csv`                -> None   (legacy, token-less)
    """
    m = _TOKEN_RE.search(Path(filename).name)
    if not m:
        return None
    tok = m.group(1)
    if tok.startswith("HFS"):
        return "hfs"
    return _FROM_DIR[tok]


def depth_from_csv_name(filename: str) -> Optional[int]:
    m = _DEPTH_RE.search(Path(filename).name)
    return int(m.group(1)) if m else None


def strategy_of_table(csv_path: str | Path) -> str:
    """The strategy a table was generated with, from its location and its name.

    The directory level is authoritative when present (`.../training_data/BFS/<inst>/`);
    the file token must agree with it. Without a strategy directory the token decides,
    and a token-less table is LEGACY_STRATEGY.
    """
    p = Path(csv_path)
    from_name = strategy_from_csv_name(p.name)
    from_dir = strategy_from_dir_name(p.parent.parent.name) if len(p.parents) >= 2 else None
    if from_dir is not None:
        if from_name is not None and from_name != from_dir:
            raise ValueError(
                f"{p}: sits under a {dir_name(from_dir)}/ directory but its name says "
                f"{dir_name(from_name)} -- the table was moved between strategy folders. "
                f"Refusing to guess which is right."
            )
        return from_dir
    return from_name if from_name is not None else LEGACY_STRATEGY


def tree_name(instance: str, strategy: str) -> str:
    """`CC_2_2_3__pl_4`, `bfs` -> `CC_2_2_3__pl_4@bfs`. One tree per (instance, pi_b)."""
    return f"{instance}{NAME_SEP}{normalize_strategy(strategy)}"


def split_tree_name(name: str) -> Tuple[str, Optional[str]]:
    """Inverse of tree_name; a bare instance name yields (name, None)."""
    if NAME_SEP in name:
        inst, strat = name.rsplit(NAME_SEP, 1)
        return inst, strat
    return name, None


