# discovery
# ----------------------------------------------------------------------------

def _tables_in(inst_dir: Path) -> List[Path]:
    return sorted(p for p in inst_dir.glob("*_depth_*.csv") if p.is_file())


def discover_tables(data_dir: str | Path) -> Dict[str, Dict[str, Path]]:
    """{instance: {strategy: csv_path}} for everything under a training_data dir.

    Handles BOTH layouts (strategy level present or legacy flat) but refuses a MIX
    of the two, an instance folder with two tables for the same strategy, and a
    table whose folder and name disagree -- every one of those is a generation-side
    accident that must not be papered over by "take the first match" (which is
    exactly what the previous `matches[0]` did: `_BFS_` sorts before `_S_DFS_`, so a
    folder holding both would silently have trained on BFS).
    """
    root = Path(data_dir)
    out: Dict[str, Dict[str, Path]] = {}
    if not root.is_dir():
        return out
    subdirs = sorted(p for p in root.iterdir() if p.is_dir())
    strat_dirs = [p for p in subdirs if strategy_from_dir_name(p.name) is not None]
    inst_dirs = [p for p in subdirs if strategy_from_dir_name(p.name) is None]
    if strat_dirs and inst_dirs:
        # An instance dir at top level next to strategy dirs: legacy + new mixed.
        mixed_inst = [p.name for p in inst_dirs if _tables_in(p)]
        if mixed_inst:
            raise ValueError(
                f"{root}: mixes the strategy layout ({[p.name for p in strat_dirs]}) with "
                f"legacy instance folders at top level ({mixed_inst}). Move the legacy "
                f"folders under {dir_name(LEGACY_STRATEGY)}/ (they are S_DFS) or delete them."
            )

    def _add(inst: str, strat: str, csv: Path) -> None:
        slot = out.setdefault(inst, {})
        if strat in slot:
            raise ValueError(
                f"instance {inst!r} has two tables for strategy {dir_name(strat)}: "
                f"{slot[strat]} and {csv}. One tree per (instance, strategy); remove one."
            )
        slot[strat] = csv

    for sd in strat_dirs:
        strat = strategy_from_dir_name(sd.name)
        for inst_dir in sorted(p for p in sd.iterdir() if p.is_dir()):
            for csv in _tables_in(inst_dir):
                got = strategy_of_table(csv)          # validates dir-vs-token agreement
                assert got == strat
                _add(inst_dir.name, strat, csv)
    for inst_dir in inst_dirs:
        for csv in _tables_in(inst_dir):
            _add(inst_dir.name, strategy_of_table(csv), csv)
    return out


def available_strategies(tables: Dict[str, Dict[str, Path]]) -> List[str]:
    found = {s for per in tables.values() for s in per}
    return [s for s in STRATEGIES if s in found]


def select_tables(
    tables: Dict[str, Dict[str, Path]],
    strategies: Optional[Iterable[str]] = None,
    *,
    verbose: bool = True,
) -> List[Path]:
    """The CSVs to train on, in (instance, strategy) order.

    `strategies=None` -> every strategy found on disk. Otherwise every requested
    strategy must exist for at least one instance (else ValueError -- the user asked
    for a pi_b that was never generated), and an instance lacking one of the
    requested strategies is reported and skipped for THAT strategy only.
    """
    avail = available_strategies(tables)
    if strategies is None:
        wanted = avail
    else:
        wanted = [normalize_strategy(s) for s in strategies]
        missing = [s for s in wanted if s not in avail]
        if missing:
            raise ValueError(
                f"requested strategies {[dir_name(s) for s in missing]} were never "
                f"generated here; available: {[dir_name(s) for s in avail] or 'none'}. "
                f"Generate them (create_all_training_data.py --dataset-generation ...) "
                f"or drop them from --strategies."
            )
    out: List[Path] = []
    for inst in sorted(tables):
        per = tables[inst]
        for s in wanted:
            if s in per:
                out.append(per[s])
            elif verbose:
                print(f"[strategies] {inst}: no {dir_name(s)} table -- skipped for that "
                      f"strategy (has {[dir_name(x) for x in per]})")
    return out


def tables_under(data_dir: str | Path, strategies: Optional[Iterable[str]] = None,
                 *, verbose: bool = True) -> List[Path]:
    """discover + select in one call."""
    return select_tables(discover_tables(data_dir), strategies, verbose=verbose)


def describe(tables: Dict[str, Dict[str, Path]]) -> str:
    """One line per instance: which strategies it has."""
    lines = []
    for inst in sorted(tables):
        lines.append(f"  {inst:28} {' '.join(dir_name(s) for s in STRATEGIES if s in tables[inst])}")
    return "\n".join(lines)


def parse_strategy_list(values: Sequence[str]) -> List[str]:
    """CLI helper: ['all'] or ['BFS,HFS'] or ['bfs', 's-dfs'] -> canonical ids, in
    STRATEGIES order, deduplicated."""
    flat: List[str] = []
    for v in values:
        flat.extend(x for x in str(v).replace(",", " ").split() if x)
    if any(x.lower() == "all" for x in flat):
        return list(STRATEGIES)
    got = {normalize_strategy(x) for x in flat}
    return [s for s in STRATEGIES if s in got]
